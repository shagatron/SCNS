test('embedded loading, error, retry and empty states stay within their mode',async({page})=>{
  await open(page)
  let release!:()=>void
  const blocked=new Promise<void>(resolve=>{release=resolve})
  await page.route('**'+endpoint,async route=>{await blocked;await route.fulfill({status:503,json:{error:{code:'demo_unavailable',message:'Simulated layout offline.'}}})})
  await page.getByRole('tab',{name:'Indoor demo',exact:true}).click()
  await expect(page.getByText('Loading demonstration rooms and floors…')).toBeVisible()
  await expect(page.getByText(qualification,{exact:true})).toBeVisible()
  await page.getByRole('link',{name:'Skip to route planner',exact:true}).focus()
  await page.keyboard.press('Enter')
  await expect(panel(page)).toBeFocused()
  await outdoor(page)
  release()
  await expect(panel(page).getByRole('alert',{includeHidden:true})).toContainText('Simulated layout offline.')
  await expect(page.getByText('Simulated layout offline.',{exact:true})).not.toBeVisible()
  await page.getByRole('tab',{name:'Indoor demo',exact:true}).click()
  await page.unroute('**'+endpoint)
  await page.getByRole('button',{name:'Retry demonstration',exact:true}).click()
  await expect(page.getByLabel('Start room')).toBeVisible()
  const data=await (await page.request.get(endpoint)).json()
  await page.route('**'+endpoint,route=>route.fulfill({json:{...data,rooms:[]}}))
  await page.reload()
  await expect(page.getByText('No demonstration rooms available',{exact:true})).toBeVisible()
  await expect(page.getByLabel('Start room')).toHaveCount(0)
  await outdoor(page)
  await expect(page.getByLabel('Destination',{exact:true})).toBeVisible()
})
