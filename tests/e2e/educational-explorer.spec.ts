test('late outdoor and indoor responses never replace active mode, state, focus or error',async({page})=>{
  await open(page)
  let finishOutdoor!:()=>void
  const waitingOutdoor=new Promise<void>(resolve=>{finishOutdoor=resolve})
  await page.route('**/api/v1/routes',async route=>{const response=await route.fetch();await waitingOutdoor;await route.fulfill({response})})
  await page.getByLabel('Destination',{exact:true}).selectOption({label:'Library'})
  await page.getByRole('button',{name:'Find walking route',exact:true}).click()
  await expect(page.getByText('Calculating a route through mapped paths…')).toBeVisible()
  await indoor(page)
  await page.getByLabel('Destination room',{exact:true}).selectOption({label:'Demo Classroom C · First floor'})
  await page.getByRole('tab',{name:'Indoor demo',exact:true}).focus()
  finishOutdoor()
  await expect(page.locator('.route-metrics')).toContainText('257')
  await expect(page.getByRole('tab',{name:'Indoor demo',exact:true})).toBeFocused()
  expect(new URL(page.url()).searchParams.get('explorer')).toBe('indoor-demo')
  expect(new URL(page.url()).searchParams.get('demo_to')).toBe(await page.getByLabel('Destination room').inputValue())
  await expect(page.locator('#outdoor-panel')).not.toBeVisible()
  let finishIndoor!:()=>void
  const waitingIndoor=new Promise<void>(resolve=>{finishIndoor=resolve})
  await page.route('**'+endpoint+'/routes',async route=>{await waitingIndoor;await route.fulfill({status:503,json:{error:{code:'simulated_failure',message:'Delayed demo failure.'}}})})
  await page.getByRole('button',{name:'Find demo directions',exact:true}).click()
  await expect(page.getByText('Computing a route over the authored graph…')).toBeVisible()
  await outdoor(page)
  await page.getByRole('tab',{name:'Outdoor',exact:true}).focus()
  finishIndoor()
  await expect(panel(page).locator('[role="alert"]')).toContainText('Delayed demo failure.')
  await expect(page.getByRole('tab',{name:'Outdoor',exact:true})).toBeFocused()
  expect(new URL(page.url()).searchParams.has('explorer')).toBe(false)
  await expect(page.getByText('Delayed demo failure.',{exact:true})).not.toBeVisible()
  await expect(page.locator('.route-metrics')).toBeVisible()
  await indoor(page)
  await expect(panel(page).getByRole('alert',{includeHidden:true})).toContainText('Delayed demo failure.')
  await page.unroute('**'+endpoint+'/routes')
  await page.getByRole('button',{name:'Retry demo route',exact:true}).click()
  await expect(page.getByText('Computed demonstration route',{exact:true})).toBeVisible()
})

