test.use({trace:'off',screenshot:'off',video:'off',actionTimeout:15000})
const endpoint='/api/v1/educational/indoor-school'
const qualification='Demonstration layout — not an actual MUJ floorplan.'
// Metadata-response simulation over a disposable synthetic release. Not actual
// Windows/MUJ data, source publication, real-device GPS or field verification.
async function open(page:Page, anchor = true) {
  await page.emulateMedia({reducedMotion:'reduce'})
  await page.route('**/api/v1/campuses',async route=>{
    const response=await route.fetch(),all=await response.json()
    await route.fulfill({response,json:all.map((c:object,i:number)=>i===0?{...c,code:'MUJ',is_demo:false,name:'Simulated MUJ explorer integration'}:c)})
  })
  await page.goto(anchor ? '/#explorer' : '/')
  await expect(page.getByRole('tab',{name:'Outdoor',exact:true})).toHaveAttribute('aria-selected','true')
  await expect(page.getByLabel('Destination',{exact:true})).toBeVisible()
  return (await page.request.get(endpoint)).json()
}
async function indoor(page:Page) {
  await page.getByRole('tab',{name:'Indoor demo',exact:true}).click()
  await expect(page.getByLabel('Start room',{exact:true})).toBeVisible()
}
async function choose(page:Page,from:string,to:string) {
  const data=await (await page.request.get(endpoint)).json()
  await page.getByLabel('Start room',{exact:true}).selectOption(data.rooms.find((r:{name:string})=>r.name===from).id)
  await page.getByLabel('Destination room',{exact:true}).selectOption(data.rooms.find((r:{name:string})=>r.name===to).id)
  await page.getByRole('button',{name:'Find demo directions',exact:true}).click()
}
const outdoor=(page:Page)=>page.getByRole('tab',{name:'Outdoor',exact:true}).click()
const panel=(page:Page)=>page.locator('#indoor-demo-panel')
const lines=(page:Page,n:number)=>expect(panel(page).locator('.campus-map path[stroke-width="6"]')).toHaveCount(n)
function out(project:string) {const p=resolve(process.env.SCNS_INTEGRATED_OUTPUT??'test-results/educational-explorer',project);mkdirSync(p,{recursive:true});return p}

