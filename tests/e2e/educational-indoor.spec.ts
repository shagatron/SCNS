import { expect, test, type Page } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'
import { mkdirSync } from 'node:fs'
import { resolve } from 'node:path'

test.use({trace:'off',screenshot:'off',video:'off',actionTimeout:15000})
const endpoint='/api/v1/educational/indoor-school'
const qualification='Demonstration layout — not an actual MUJ floorplan.'
async function open(page:Page) {
  await page.emulateMedia({reducedMotion:'reduce'})
  await page.goto('/indoor-demo')
  await expect(page.getByRole('button',{name:'Find demo directions',exact:true})).toBeEnabled()
  await expect(page.getByText('Loading demonstration floor image…')).toHaveCount(0)
  return (await page.request.get(endpoint)).json()
}
async function choose(page:Page,from:string,to:string) {
  const data=await (await page.request.get(endpoint)).json()
  await page.getByLabel('Start room',{exact:true}).selectOption(data.rooms.find((r:{name:string})=>r.name===from).id)
  await page.getByLabel('Destination room',{exact:true}).selectOption(data.rooms.find((r:{name:string})=>r.name===to).id)
  await page.getByRole('button',{name:'Find demo directions',exact:true}).click()
}
async function lines(page:Page,n:number) { await expect(page.locator('.campus-map path[stroke-width="6"]')).toHaveCount(n) }
function out(project:string) {const p=resolve(process.env.SCNS_SCHOOL_OUTPUT??'test-results/educational-indoor',project);mkdirSync(p,{recursive:true});return p}

test('computed same/cross/reverse/disconnected paths, floor sections, reload and independent directions',async({page},info)=>{
  test.setTimeout(90000)
  const data=await open(page),dir=out(info.project.name)
  await expect(page.getByText(qualification,{exact:true})).toHaveCount(3)
  await choose(page,'Demo Classroom A','Demo Library')
  await expect(page.getByText('3 authored traversals · Directions only.',{exact:false})).toBeVisible()
  await lines(page,3)
  await page.locator('.demo-viewer').screenshot({path:`${dir}/ground-same-floor.png`})
  await choose(page,'Demo Classroom A','Demo Classroom C')
  await expect(page.getByText('9 authored traversals · Directions only.',{exact:false})).toBeVisible()
  await expect(page.getByText('Take Demo Stairs from Ground floor to First floor. No verified step-free alternative is demonstrated.',{exact:true})).toBeVisible()
  await lines(page,4)
  await page.locator('.demo-viewer').screenshot({path:`${dir}/ground-cross-floor.png`})
  const transition=page.locator('.demo-directions li').filter({hasText:'Take Demo Stairs'})
  await transition.getByRole('button',{name:'Show First floor',exact:true}).click()
  await expect(page.getByLabel('View demonstration floor')).toHaveValue(data.floors[1].id)
  await lines(page,4)
  await expect(page.getByText('Loading demonstration floor image…')).toHaveCount(0)
  await page.locator('.demo-viewer').screenshot({path:`${dir}/first-cross-floor.png`})
  await page.screenshot({path:`${dir}/computed-cross-floor.png`,fullPage:true})
  await page.reload()
  await expect(page.getByText('9 authored traversals · Directions only.',{exact:false})).toBeVisible()
  await expect(page.getByLabel('View demonstration floor')).toHaveValue(data.floors[1].id)
  await lines(page,4)
  await page.getByRole('button',{name:'Hide demonstration map',exact:true}).click()
  await expect(page.getByRole('region',{name:'Demonstration directions'})).toBeVisible()
  await expect(page.getByText('Distance unknown · ETA unavailable',{exact:true})).toBeVisible()
  await expect(page.locator('.demo-directions')).not.toContainText(/\b\d+\s*(metres|min)\b/)
  await page.getByRole('button',{name:'Show demonstration map',exact:true}).click()
  await choose(page,'Demo Classroom C','Demo Classroom A')
  await expect(page.getByText('Take Demo Stairs from First floor to Ground floor. No verified step-free alternative is demonstrated.',{exact:true})).toBeVisible()
  await expect(page.getByLabel('View demonstration floor')).toHaveValue(data.floors[1].id)
  await lines(page,4)
  await choose(page,'Demo Classroom A','Demo Disconnected Room')
  await expect(page.getByRole('alert')).toContainText('has no authored graph connection')
  await lines(page,0)
  await expect(page.getByLabel('Destination room')).toHaveValue(data.rooms.find((r:{name:string})=>r.name==='Demo Disconnected Room').id)
  await expect(page.getByRole('region',{name:'Demonstration directions'})).toHaveCount(0)
  await choose(page,'Demo Classroom A','Demo Classroom A')
  await expect(page.getByText('Start and destination are the same demo room.',{exact:false})).toBeVisible()
  await expect(page.getByText('Distance unknown · ETA unavailable',{exact:true})).toBeVisible()
})

test('keyboard zoom/pan/floor controls, mobile width and accessibility',async({page})=>{
  await open(page)
  const map=page.locator('.campus-map'),image=map.locator('.leaflet-image-layer')
  await map.focus()
  const before=await image.getAttribute('style')
  await page.keyboard.press('Equal')
  await expect.poll(()=>image.getAttribute('style')).not.toBe(before)
  const panBefore=await map.locator('.leaflet-map-pane').getAttribute('style')
  await page.keyboard.press('ArrowRight')
  await expect.poll(()=>map.locator('.leaflet-map-pane').getAttribute('style')).not.toBe(panBefore)
  await page.getByRole('button',{name:'Fit floor plan'}).click()
  await page.getByRole('button',{name:'Find demo directions',exact:true}).focus()
  await page.keyboard.press('Enter')
  await expect(page.getByText('Computed demonstration route',{exact:true})).toBeVisible()
  await page.mouse.move(0,0)
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy()
  const result=await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa','wcag21aa','wcag22aa']).analyze()
  expect(result.violations).toEqual([])
})

test('loading/error/retry/empty/image failure states retain controls and text',async({page})=>{
  await page.route('**'+endpoint,async route=>{await new Promise(r=>setTimeout(r,250));await route.fulfill({status:503,json:{error:{code:'synthetic_failure',message:'Synthetic demonstration unavailable.'}}})})
  await page.goto('/indoor-demo')
  await expect(page.getByText('Loading demonstration rooms and floors…')).toBeVisible()
  await expect(page.getByRole('alert')).toContainText('Synthetic demonstration unavailable.')
  await page.unroute('**'+endpoint)
  await page.getByRole('button',{name:'Retry demonstration',exact:true}).click()
  await expect(page.getByLabel('Start room')).toBeVisible()
  await page.route('**'+endpoint+'/routes',route=>route.fulfill({status:503,json:{error:{code:'synthetic_failure',message:'Synthetic route temporarily unavailable.'}}}))
  await page.getByRole('button',{name:'Find demo directions',exact:true}).click()
  await expect(page.locator('#demo-planner [role="alert"]')).toContainText('Synthetic route temporarily unavailable.')
  await page.unroute('**'+endpoint+'/routes')
  await page.getByRole('button',{name:'Retry demo route',exact:true}).click()
  await expect(page.getByText('Computed demonstration route',{exact:true})).toBeVisible()
  await page.route('**/demos/indoor-school/v1/*.svg',route=>route.abort())
  await page.reload()
  await expect(page.getByText('Demonstration floor image unavailable. Text directions remain usable.',{exact:true})).toBeVisible()
  await expect(page.getByRole('region',{name:'Demonstration directions'})).toBeVisible()
  await page.unroute('**/demos/indoor-school/v1/*.svg')
  await page.getByRole('button',{name:'Retry floor image',exact:true}).click()
  await expect(page.getByText('Demonstration floor image unavailable.',{exact:false})).toHaveCount(0)
  const data=await (await page.request.get(endpoint)).json()
  await page.route('**'+endpoint,route=>route.fulfill({json:{...data,rooms:[]}}))
  await page.reload()
  await expect(page.getByText('No demonstration rooms available',{exact:true})).toBeVisible()
  await expect(page.getByLabel('Start room')).toHaveCount(0)
})

test('MUJ entry is additive, qualification precedes entry, return restores campus; Demo baseline unchanged',async({page},info)=>{
  // Metadata response simulation over an isolated synthetic published release.
  // NOT actual Windows/MUJ publication or real-campus dataset verification.
  let selected=''
  await page.route('**/api/v1/campuses',async route=>{
    const response=await route.fetch(),all=await response.json()
    selected=all[0].id
    await route.fulfill({response,json:all.map((c:{id:string})=>c.id===selected?{...c,code:'MUJ',is_demo:false,name:'Simulated MUJ educational entry'}:c)})
  })
  await page.goto('/')
  await expect(page.getByRole('link',{name:'Indoor navigation demo ↗',exact:true})).toBeVisible()
  await expect(page.getByText(qualification,{exact:true})).toBeVisible()
  await expect(page.getByAltText('Manipal University Jaipur emblem')).toBeVisible()
  await page.locator('#intro').screenshot({path:`${out(info.project.name)}/muj-entry-simulated.png`})
  await page.getByRole('link',{name:'Indoor navigation demo ↗',exact:true}).click()
  await expect(page.getByRole('heading',{name:'Indoor navigation demo',exact:true})).toBeVisible()
  await page.getByRole('link',{name:'← Return to campus explorer',exact:true}).click()
  await expect(page.getByLabel('Explore campus',{exact:true})).toHaveValue(selected)
  await expect(page.getByRole('link',{name:'Places',exact:true})).toBeVisible()
  await page.getByLabel('Destination',{exact:true}).selectOption({label:'Library'})
  await page.getByRole('button',{name:'Find walking route',exact:true}).click()
  await expect(page.locator('.route-metrics')).toContainText('257')
  await expect(page.locator('.route-metrics')).toContainText('4')
  await expect(page.getByText('Arrive at Library.',{exact:true})).toBeVisible()
  await page.unroute('**/api/v1/campuses')
  await page.goto('/')
  await expect(page.getByText('Synthetic demo.',{exact:true})).toBeVisible()
  await expect(page.getByRole('link',{name:'Indoor navigation demo ↗',exact:true})).toHaveCount(0)
})
