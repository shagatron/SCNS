test.use({ trace: 'off', screenshot: 'off', video: 'off' })
const fixture = (name: string) => resolve(process.cwd(), '../data/demo/floorplans', name)
async function login(page: Page, role: string, campus: string) {
  await page.goto('/admin')
  await page.getByLabel('Username', { exact: true }).fill(`browser-${role}`)
  await page.getByLabel('Password', { exact: true }).fill(process.env.SCNS_E2E_PASSWORD!)
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Admin dashboard' })).toBeVisible()
  await page.getByRole('combobox', { name: 'Assigned campus' }).selectOption({ label: campus })
  await page.getByRole('button', { name: 'Floors and floorplans', exact: true }).click()
}
async function draft(page: Page) {
  const response = page.waitForResponse(r => r.url().endsWith('/drafts') && r.request().method() === 'POST')
  await page.getByRole('button', { name: 'Create draft from published release', exact: true }).click()
  const data = await (await response).json()
  await page.getByLabel('Floor code', { exact: true }).fill('B1')
  await page.getByLabel('Floor label', { exact: true }).fill('Synthetic basement B1')
  await page.getByLabel('Floor ordering (basement negative, ground 0)', { exact: true }).fill('-1')
  const created = page.waitForResponse(r => r.url().endsWith('/floors') && r.request().method() === 'POST')
  await page.getByRole('button', { name: 'Save floor metadata', exact: true }).click()
  const floor = await (await created).json()
  await expect(page.getByRole('heading', { name: 'Synthetic basement B1', exact: true })).toBeVisible()
  return { data, floor, base: `/api/v1/admin/campuses/${data.campus_id}/drafts/${data.id}` }
}
async function warnings(page: Page) {
  await page.getByRole('textbox', { name: 'Reason after reviewing all displayed warnings', exact: true }).fill('Reviewed synthetic coverage and display-only floor limits; no indoor navigation or field survey claim.')
  await page.getByRole('button', { name: /Acknowledge all \d+ warnings with this reason/ }).click()
}

