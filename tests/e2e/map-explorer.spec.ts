// All locations below are the disposable synthetic Demo release, not Windows MUJ.
test('shared list/pin selection, keyboard card close, route actions and panel recovery', async ({ page }) => {
  await page.goto('/#explorer')
  await page.getByRole('button', { name: 'Browse places', exact: true }).click()
  await page.getByLabel('Search destinations').fill('books')
  const row = page.locator('.place-select').filter({ hasText: 'Library' })
  await row.focus(); await page.keyboard.press('Enter')
  const card = page.getByRole('region', { name: 'Selected place details' })
  await expect(card).toBeFocused()
  await expect(card.getByRole('heading', { name: 'Library', exact: true })).toBeVisible()
  const pin = page.locator('.selected-pin[title="Select Library"]')
  await expect(pin).toHaveCount(1)
  await expect(row).toHaveAttribute('aria-pressed', 'true')
  await page.keyboard.press('Escape'); await expect(row).toBeFocused()
  await expect(card).toHaveCount(0)
  await page.getByRole('button', { name: 'Select Library', exact: true }).last().focus()
  await page.keyboard.press('Enter')
  await expect(card).toBeFocused()
  await card.getByRole('button', { name: 'Set as start', exact: true }).click()
  await expect(page.getByLabel('Starting point', { exact: true })).toBeFocused()
  await expect(page.getByLabel('Starting point', { exact: true }).locator('option:checked')).toHaveText('Library')
  await page.getByLabel('Destination', { exact: true }).selectOption({ label: 'Main Gate' })
  await page.getByRole('button', { name: 'Swap start and destination' }).click()
  await page.getByRole('button', { name: 'Find walking route' }).click()
  await expect(page.getByText('Arrive at Library.', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Collapse panel', exact: true }).click()
  await expect(page.getByLabel('Destination', { exact: true })).not.toBeVisible()
  await expect(page.getByRole('complementary', { name: 'Route safety and connection' })).toContainText('257m')
  await expect(page.getByRole('button', { name: 'Check restrictions', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Expand panel', exact: true }).click()
  await expect(page.getByText('Arrive at Library.', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Hide map', exact: true }).click()
  await expect(page.getByRole('region', { name: 'Route directions' })).toBeVisible()
  await page.getByRole('button', { name: 'Collapse panel', exact: true }).click()
  await page.getByRole('link', { name: 'Skip to route planner' }).focus()
  await page.keyboard.press('Enter')
  await expect(page.locator('#planner')).toBeFocused()
  await expect(page.getByLabel('Destination', { exact: true })).toBeVisible()
})

test('five viewport workspace captures, touch controls, attribution and no keyboard overflow', async ({ page }, info) => {
  test.skip(info.project.name.startsWith('mobile'), 'One explicit five-width sweep covers both layouts; mobile project covers journeys separately.')
  test.setTimeout(120000)
  await page.emulateMedia({ reducedMotion: 'reduce' })
  for (const width of [320, 360, 390, 768, 1440]) {
    await page.setViewportSize({ width, height: 960 })
    await page.goto('/#explorer')
    await page.getByRole('button', { name: 'Browse places', exact: true }).click()
    await expect(page.locator('.place-select').first()).toBeVisible()
    await page.getByLabel('Search destinations').focus()
    await page.getByLabel('Search destinations').fill('books')
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    const search = await page.getByLabel('Search destinations').boundingBox()
    expect(search!.x).toBeGreaterThanOrEqual(0); expect(search!.x + search!.width).toBeLessThanOrEqual(width)
    await page.locator('.place-select').filter({ hasText: 'Library' }).click()
    await expect(page.getByRole('region', { name: 'Selected place details' })).toBeVisible()
    if (width === 1440) {
      const card = await page.getByRole('region', { name: 'Selected place details' }).boundingBox()
      const zoom = await page.locator('.leaflet-control-zoom').boundingBox()
      expect(card && zoom).toBeTruthy()
      expect(card!.x >= zoom!.x + zoom!.width || card!.y >= zoom!.y + zoom!.height || card!.x + card!.width <= zoom!.x || card!.y + card!.height <= zoom!.y).toBe(true)
    }
    if ([390,1440].includes(width)) await page.screenshot({ path: `test-results/map-explorer/${width}-selected.png`, style: '.public-navigation, .skip-link { visibility: hidden !important; }' })
    await page.getByRole('region', { name: 'Selected place details' }).getByRole('button', { name: 'Close place details' }).click()
    await page.getByLabel('Search destinations').fill('')
    await page.locator('#explorer').evaluate(el => el.scrollIntoView({ behavior: 'instant' }))
    await page.evaluate(() => document.fonts.ready)
    await page.screenshot({ path: `test-results/map-explorer/${width}-browse.png`, style: '.public-navigation, .skip-link { visibility: hidden !important; }' })
    await expect(page.locator('.leaflet-control-attribution')).toBeVisible()
    expect(await page.locator('.campus-map').evaluate(el => getComputedStyle(el).filter)).toBe('none')
    await page.getByRole('button', { name: 'Plan route', exact: true }).click()
    await page.getByLabel('Destination', { exact: true }).selectOption({ label: 'Library' })
    await page.getByRole('button', { name: 'Find walking route' }).click()
    await expect(page.locator('.route-metrics')).toContainText('257')
    await expect(page.locator('.leaflet-overlay-pane path[stroke="#9bf3ce"][stroke-width="6"]')).toHaveCount(3)
    await page.getByRole('button', { name: 'Fit route', exact: true }).click()
    await page.locator('#explorer').evaluate(el => el.scrollIntoView({ behavior: 'instant' }))
    await page.screenshot({ path: `test-results/map-explorer/${width}-route.png`, style: '.public-navigation, .skip-link { visibility: hidden !important; }' })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    const issues = await new AxeBuilder({ page }).withTags(['wcag2a','wcag2aa','wcag21aa','wcag22aa']).analyze()
    expect(issues.violations).toEqual([])
    const button = await page.getByRole('button', { name: 'Collapse panel', exact: true }).boundingBox()
    expect(button!.height).toBeGreaterThanOrEqual(44)
  }
})

test('resize preserves an existing map instead of remounting or refitting on selection', async ({ page }) => {
  await page.goto('/#explorer')
  await expect(page.getByRole('button', { name: 'Fit campus', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Zoom in', exact: true }).click()
  const identity = await page.locator('.campus-map').evaluate(el => (el as HTMLElement & { _leaflet_id: number })._leaflet_id)
  await page.getByRole('button', { name: 'Collapse panel', exact: true }).click()
  await page.setViewportSize({ width: 768, height: 860 })
  await page.getByRole('button', { name: 'Expand panel', exact: true }).click()
  await expect.poll(() => page.locator('.campus-map').evaluate(el => (el as HTMLElement & { _leaflet_id: number })._leaflet_id)).toBe(identity)
  await expect(page.locator('.leaflet-overlay-pane svg path').first()).toBeVisible()
  await page.getByRole('button', { name: 'Fit campus', exact: true }).click()
})

