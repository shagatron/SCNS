test('shared-route place lookup errors stay by the original planner and retry recovers the route', async ({ page }) => {
  await page.goto('/#explorer')
  await page.getByLabel('Destination', {exact:true}).selectOption({label:'Library'})
  await page.getByRole('button', {name:'Find walking route'}).click()
  await expect(page.getByText('Arrive at Library.',{exact:true})).toBeVisible()
  await page.route('**/api/v1/campuses/*/places/*?*', route => route.fulfill({status:503,json:{error:{code:'service_unavailable',message:'Synthetic shared place lookup failed.'}}}))
  await page.reload()
  await expect(page.locator('#planner').getByRole('alert')).toContainText('Synthetic shared place lookup failed.')
  await expect(page.getByLabel('Destination',{exact:true}).locator('option:checked')).toHaveText('Library')
  await page.unroute('**/api/v1/campuses/*/places/*?*')
  await page.locator('#planner').getByRole('button',{name:'Try again',exact:true}).click()
  await expect(page.getByText('Arrive at Library.',{exact:true})).toBeVisible()
})
