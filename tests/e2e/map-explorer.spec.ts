test('original directory, pagination, details and sequential start/route actions stay available', async ({ page }) => {
  await page.goto('/')
  const directory = page.locator('#directory')
  await expect(directory.locator('.places-grid article')).toHaveCount(6)
  await expect(directory.getByLabel('Search destinations')).toHaveAttribute('placeholder', 'Try library, coffee, or a building code')
  await expect(directory.getByLabel('Search destinations')).toHaveAttribute('maxlength', '120')
  await page.getByRole('link', { name: 'Places', exact: true }).click()
  await expect(directory).toBeFocused()
  await expect(directory.getByRole('button', { name: 'Previous', exact: true })).toBeDisabled()
  await directory.getByRole('button', { name: 'Next', exact: true }).click()
  await expect(directory.locator('.pagination')).toContainText('showing 7–10')
  await expect(directory.locator('.places-grid article')).toHaveCount(4)
  await expect(directory.getByRole('button', { name: 'Next', exact: true })).toBeDisabled()
  await directory.getByLabel('Category', { exact: true }).selectOption('library')
  await expect(directory.locator('.pagination')).toContainText('showing 1–1')
  await expect(directory.getByRole('heading', { name: 'Library', exact: true })).toBeVisible()
  await directory.getByText('Place details', { exact: true }).click()
  await expect(directory).toContainText('Accessibility: unknown until surveyed.')
  await expect(directory).toContainText('Also known as:')
  await directory.getByRole('button', { name: 'Start at Library', exact: true }).click()
  await expect(page.getByLabel('Starting point', { exact: true })).toBeFocused()
  await expect(directory.getByRole('button', { name: 'Route to Library', exact: true })).toBeVisible()
  await page.getByLabel('Starting point', { exact: true }).selectOption({ label: 'Main Gate' })
  let requests = 0
  page.on('request', r => { if (r.url().endsWith('/api/v1/routes')) requests++ })
  await directory.getByRole('button', { name: 'Route to Library', exact: true }).click()
  await expect(page.getByLabel('Destination', { exact: true })).toBeFocused()
  expect(requests).toBe(0)
  await expect(page.getByLabel('Route preference')).toHaveValue('shortest')
  await expect(page.getByLabel('Distance policy')).toHaveValue('metric')
  const response = page.waitForResponse(r => r.url().endsWith('/api/v1/routes'))
  await page.getByRole('button', { name: 'Find walking route' }).click()
  const route = await (await response).json()
  expect(route.distance_m).toBe(256.88); expect(route.segments).toHaveLength(3)
  await page.locator('.route-controls > summary').click()
  await expect(page.getByLabel('Destination', { exact: true })).not.toBeVisible()
  await expect(page.getByRole('region', { name: 'Route directions' })).toBeVisible()
  expect(await page.locator('.route-results').evaluate(e => e.parentElement?.id)).toBe('explorer')
  await page.reload()
  await expect(page.getByText('Arrive at Library.', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Hide map', exact: true }).click()
  await expect(page.getByRole('region', { name: 'Route directions' })).toBeVisible()
})

test('search and route failures remain contextual without error-driven focus or scroll jumps', async ({ page }) => {
  await page.goto('/#directory')
  const search = page.getByLabel('Search destinations')
  let searchFailed = true
  await page.route('**/api/v1/campuses/*/search?*', route => new URL(route.request().url()).searchParams.get('q') === 'parity-error' && searchFailed
    ? route.fulfill({ status:503, json:{error:{code:'service_unavailable',message:'Synthetic directory lookup failed.'}} }) : route.continue())
  await search.fill('parity-error')
  const error = page.locator('#directory').getByRole('alert')
  await expect(error).toContainText('Synthetic directory lookup failed.')
  await expect(search).toBeFocused()
  searchFailed = false
  await error.getByRole('button', { name:'Try again', exact:true }).click()
  await expect(page.getByText('No matching places. Try another name, alias, or category.')).toBeVisible()
  await search.fill('books')
  await page.getByRole('button', { name:'Route to Library', exact:true }).click()
  await page.getByLabel('Destination', { exact:true }).selectOption({label:'Quiet Garden'})
  let release!: () => void
  const gate = new Promise<void>(resolve => { release = resolve })
  await page.route('**/api/v1/routes', async route => { const response = await route.fetch(); await gate; await route.fulfill({response}) })
  await page.getByRole('button', { name:'Find walking route' }).click()
  await expect(page.locator('#planner').getByRole('status')).toContainText('Calculating a route through mapped paths…')
  const before = await page.evaluate(() => ({y:scrollY,focus:document.activeElement?.id}))
  release()
  await expect(page.locator('#planner').getByRole('alert')).toContainText('No permitted walking route connects these locations. Try a different mapped start or destination.')
  const after = await page.evaluate(() => ({y:scrollY,focus:document.activeElement?.id}))
  expect(Math.abs(after.y-before.y)).toBeLessThanOrEqual(2)
  expect(after.focus).toBe(before.focus)
  await expect(page.getByLabel('Destination', { exact:true }).locator('option:checked')).toHaveText('Quiet Garden')
  await expect(page.locator('#planner').getByRole('button', {name:'Find walking route'})).toBeEnabled()
})

test('every original map place remains and a marker directly chooses destination and opens controls', async ({ page }) => {
  const initialResponse = page.waitForResponse(r => r.url().includes('/search?limit=100'))
  await page.goto('/#explorer')
  const initial = await (await initialResponse).json()
  await expect(page.locator('.scns-pin')).toHaveCount(initial.items.filter((p: {point:unknown}) => p.point).length)
  await expect(page.locator('.place-label')).toHaveCount(initial.items.filter((p: {point:unknown}) => p.point).length)
  await page.locator('.route-controls > summary').click()
  const marker = page.getByTitle('Map destination: Library',{exact:true})
  expect(await marker.evaluate(e => (e as HTMLElement).tabIndex)).toBe(-1)
  await marker.click()
  await expect(page.getByLabel('Destination', { exact:true })).toBeFocused()
  await expect(page.getByLabel('Destination', { exact:true }).locator('option:checked')).toHaveText('Library')
  await expect(page.getByRole('region', {name:'Selected place details'})).toHaveCount(0)
  const id = await page.locator('.campus-map').evaluate(e => (e as HTMLElement & {_leaflet_id:number})._leaflet_id)
  await page.getByRole('button', {name:'Zoom in',exact:true}).click()
  await page.setViewportSize({width:768,height:900})
  await page.evaluate(() => new Promise<void>(resolve => requestAnimationFrame(() => requestAnimationFrame(() => resolve()))))
  await page.getByRole('button', {name:'Fit campus',exact:true}).click()
  expect(await page.locator('.campus-map').evaluate(e => (e as HTMLElement & {_leaflet_id:number})._leaflet_id)).toBe(id)
  await expect(marker).toBeVisible()
})

