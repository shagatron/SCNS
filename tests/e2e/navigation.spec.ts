import { expect, test } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'

test('search → select → computed path and text directions on a small screen', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByText('Campus service connected')).toBeVisible()
  await page.getByLabel('Search destinations').fill('books')
  await page.getByRole('button', { name: 'Route to Library', exact: true }).click()
  const responsePromise = page.waitForResponse(response => response.url().endsWith('/api/v1/routes'))
  await page.getByRole('button', { name: 'Find walking route' }).click()
  const result = await (await responsePromise).json()
  expect(result.segments.length).toBeGreaterThan(1)
  expect(result.distance_m).toBeGreaterThan(100)
  await expect(page.getByRole('heading', { name: 'Your route is ready' })).toBeVisible()
  await expect(page.getByText('Arrive at Library.', { exact: true })).toBeVisible()
  await expect(page.locator('.leaflet-overlay-pane path[stroke="#146855"]')).toHaveCount(result.segments.length)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
  await page.getByRole('button', { name: 'Hide map' }).click()
  await expect(page.getByRole('region', { name: 'Route directions' })).toBeVisible()
  await page.screenshot({ path: `test-results/${test.info().project.name}-route.png`, fullPage: true })
})

test('no route, same-place arrival, step-free constraints and swap', async ({ page }) => {
  await page.goto('/')
  await page.getByLabel('Destination', { exact: true }).selectOption({ label: 'Quiet Garden' })
  await page.getByRole('button', { name: 'Find walking route' }).click()
  await expect(page.getByRole('alert')).toContainText('No permitted walking route')
  await page.getByLabel('Destination', { exact: true }).selectOption({ label: 'Main Gate' })
  await page.getByRole('button', { name: 'Find walking route' }).click()
  await expect(page.getByRole('heading', { name: 'You’re already there' })).toBeVisible()
  await page.getByLabel('Destination', { exact: true }).selectOption({ label: 'East Exit' })
  await page.getByLabel('Route preference').selectOption('step_free')
  await page.getByRole('button', { name: 'Find walking route' }).click()
  await expect(page.getByRole('alert')).toContainText('No verified step-free route')
  await page.getByRole('button', { name: 'Swap start and destination' }).click()
  await expect(page.getByLabel('Starting point')).toHaveValue(await page.getByLabel('Starting point').locator('option', { hasText: 'East Exit' }).getAttribute('value') as string)
})

test('keyboard route and automated accessibility check', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByLabel('Destination', { exact: true }).locator('option', { hasText: 'Library' })).toBeAttached()
  await expect(page.getByRole('button', { name: 'Find walking route' })).toBeEnabled()
  await page.getByLabel('Destination', { exact: true }).focus()
  await page.keyboard.press('l')
  await page.keyboard.press('Tab')
  await page.keyboard.press('Tab')
  await page.keyboard.press('Tab')
  await page.keyboard.press('Enter')
  await expect(page.getByRole('heading', { name: 'Your route is ready' })).toBeVisible()
  const violations = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa', 'wcag22aa']).analyze()
  expect(violations.violations).toEqual([])
})

test('API failure can recover and empty searches stay honest', async ({ page }) => {
  await page.route('**/api/v1/campuses', route => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ error: { code: 'service_unavailable', message: 'Campus data is temporarily unavailable.' } }) }))
  await page.goto('/')
  await expect(page.getByRole('alert')).toContainText('temporarily unavailable')
  await page.unroute('**/api/v1/campuses')
  await page.getByRole('button', { name: 'Try again' }).click()
  await page.getByLabel('Search destinations').fill('nonexistent observatory')
  await expect(page.getByText('No matching places. Try another name, alias, or category.')).toBeVisible()
})

test('map failure preserves text-only navigation and offline disables new requests', async ({ page, context }) => {
  await page.route('**/api/v1/campuses/*/map?*', route => route.abort())
  await page.goto('/')
  await page.getByLabel('Destination', { exact: true }).selectOption({ label: 'Library' })
  await page.getByRole('button', { name: 'Find walking route' }).click()
  await expect(page.getByText('Arrive at Library.', { exact: true })).toBeVisible()
  await context.setOffline(true)
  await expect(page.getByText('Offline · connection needed for new routes')).toBeVisible()
  await expect(page.getByRole('button', { name: 'Find walking route' })).toBeDisabled()
  await context.setOffline(false)
})
