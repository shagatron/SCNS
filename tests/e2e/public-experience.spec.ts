import { expect, test } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'

// Public-only screenshots contain invented published locations, never admin credentials.
test('editorial introduction, real counts and direct explorer work at four widths with reduced motion', async ({ page }) => {
  test.setTimeout(120000) // Four viewports, real routes, screenshots and accessibility scans.
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Find your way across campus.' })).toBeVisible()
  await expect(page.getByText('Public destinations', { exact: true })).toBeVisible()
  const campusId = await page.getByLabel('Explore campus', { exact: true }).inputValue()
  const published = await (await page.request.get(`/api/v1/campuses/${campusId}/search?limit=100`)).json()
  await expect(page.locator('.campus-figures > div').filter({ has: page.getByText('Public destinations', { exact: true }) }).locator('strong')).toHaveText(String(published.total))
  await expect(page.getByText('Mapped buildings', { exact: true })).toBeVisible()
  await expect(page.getByText('Illustrative graph · not a navigable campus map')).toBeVisible()
  for (const width of [320, 360, 768, 1440]) {
    await page.setViewportSize({ width, height: 1000 })
    await page.goto('/')
    await expect(page.getByText('Campus service connected')).toBeVisible()
    await page.evaluate(() => document.fonts.ready)
    expect(await page.evaluate(() => [...document.fonts].some(font => font.family === 'SCNS Inter' && font.status === 'loaded'))).toBeTruthy()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
    expect(await page.evaluate(() => getComputedStyle(document.documentElement).scrollBehavior)).toBe('auto')
    const headline = await page.locator('#intro-heading').boundingBox()
    expect(headline!.x).toBeGreaterThanOrEqual(0); expect(headline!.x + headline!.width).toBeLessThanOrEqual(width)
    await page.screenshot({ path: `test-results/redesign/${test.info().project.name}-${width}-homepage.png` })
    if (width === 1440) {
      for (const id of ['overview', 'how', 'directory']) await page.locator(`#${id}`).screenshot({ path: `test-results/redesign/${test.info().project.name}-${id}.png`, style: '.public-navigation, .skip-link { visibility: hidden !important; }' })
    }
    await page.getByRole('link', { name: 'Explore campus', exact: true }).click()
    await expect(page.getByLabel('Destination', { exact: true })).toBeVisible()
    await expect(page.getByRole('link', { name: 'Explore ↗', exact: true })).toHaveAttribute('aria-current', 'location')
    expect(await page.locator('#explorer').evaluate(el => el.getBoundingClientRect().top)).toBeLessThan(200)
    await page.getByLabel('Destination', { exact: true }).selectOption({ label: 'Library' })
    const response = page.waitForResponse(r => r.url().endsWith('/api/v1/routes'))
    await page.getByRole('button', { name: 'Find walking route' }).click()
    const route = await (await response).json()
    expect(route.distance_m).toBe(256.88); expect(route.segments).toHaveLength(3)
    await expect(page.getByRole('heading', { name: 'Your route is ready' })).toBeVisible()
    if ([360, 1440].includes(width)) await page.locator('#explorer').screenshot({ path: `test-results/redesign/${test.info().project.name}-${width}-explorer-controls.png` })
    await page.locator('.route-controls > summary').click()
    await expect(page.getByLabel('Destination', { exact: true })).not.toBeVisible()
    await expect(page.getByText('Arrive at Library.', { exact: true })).toBeVisible()
    await page.locator('#explorer').scrollIntoViewIfNeeded()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
    await page.locator('#explorer').screenshot({ path: `test-results/redesign/${test.info().project.name}-${width}-explorer.png` })
    const violations = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa', 'wcag22aa']).analyze()
    expect(violations.violations).toEqual([])
  }
})

test('keyboard skip, directory selection, collapsed controls and reload preserve the actual route', async ({ page }) => {
  await page.goto('/#explorer')
  await expect(page.getByLabel('Destination', { exact: true })).toBeVisible()
  await page.locator('.route-controls > summary').click()
  await page.getByRole('link', { name: 'Places', exact: true }).click()
  await page.getByLabel('Search destinations').fill('books')
  await page.getByRole('button', { name: 'Route to Library', exact: true }).click()
  await expect(page.getByLabel('Destination', { exact: true })).toBeFocused()
  expect((await page.getByLabel('Destination', { exact: true }).boundingBox())!.y).toBeGreaterThan(90)
  await page.getByRole('button', { name: 'Find walking route' }).click()
  await expect(page.getByText('Arrive at Library.', { exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByText('Arrive at Library.', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Hide map' }).click()
  await expect(page.getByRole('region', { name: 'Route directions' })).toBeVisible()
  await page.goto('/')
  await page.keyboard.press('Tab')
  await expect(page.getByRole('link', { name: 'Skip to route planner' })).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(page.locator('#planner')).toBeFocused()
})

test('empty and failed public data never invent overview figures or lose direct access', async ({ page }) => {
  await page.route('**/api/v1/campuses', r => r.fulfill({ json: [] }))
  await page.goto('/#explorer')
  await expect(page.getByRole('heading', { name: 'No published campus yet' })).toBeVisible()
  await expect(page.locator('.campus-figures')).toHaveCount(0)
  await page.unroute('**/api/v1/campuses')
  await page.route('**/api/v1/campuses', r => r.fulfill({ status: 503, json: { error: { code: 'service_unavailable', message: 'Campus data is temporarily unavailable.' } } }))
  await page.reload()
  await expect(page.getByRole('alert')).toContainText('temporarily unavailable')
  await page.unroute('**/api/v1/campuses')
  await page.getByRole('button', { name: 'Try again' }).click()
  await expect(page.getByLabel('Destination', { exact: true })).toBeVisible()
})

test('native section navigation and visible content survive missing reveal initialization', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await page.addInitScript(() => { Object.defineProperty(window, 'IntersectionObserver', { configurable: true, value: undefined }) })
  await page.goto('/')
  await expect(page.getByText('Public destinations', { exact: true })).toBeVisible()
  expect(await page.evaluate(() => getComputedStyle(document.documentElement).scrollBehavior)).toBe('smooth')
  await page.getByRole('link', { name: 'Places', exact: true }).click()
  await expect(page.getByRole('link', { name: 'Places', exact: true })).toHaveAttribute('aria-current', 'location')
  await expect(page.getByRole('heading', { name: 'Places worth finding.' })).toBeVisible()
  expect(await page.locator('#directory-heading').evaluate(el => getComputedStyle(el).opacity)).toBe('1')
  await page.getByLabel('Search destinations').fill('books')
  await page.getByRole('button', { name: 'Route to Library', exact: true }).click()
  await expect(page.getByLabel('Destination', { exact: true })).toBeFocused()
})

test('public styles do not restyle the existing anonymous admin login', async ({ page }) => {
  await page.goto('/#explorer')
  await expect(page.getByLabel('Destination', { exact: true })).toBeVisible()
  const publicStyle = await page.getByRole('button', { name: 'Find walking route' }).evaluate(el => getComputedStyle(el).borderRadius)
  expect(publicStyle).toBe('2px')
  await page.goto('/admin')
  await expect(page.getByRole('heading', { name: 'Admin sign in' })).toBeVisible()
  await expect(page.locator('.public-app')).toHaveCount(0)
  expect(await page.getByRole('button', { name: 'Sign in', exact: true }).evaluate(el => getComputedStyle(el).borderRadius)).not.toBe(publicStyle)
})


test('failed published-release metadata remains at the direct explorer and recovery preserves that entry', async ({ page }) => {
  await page.route('**/api/v1/campuses/*/release', r => r.fulfill({ status: 503, json: { error: { code: 'service_unavailable', message: 'Published-release metadata temporarily unavailable.' } } }))
  await page.goto('/#explorer')
  await expect(page.locator('#explorer').getByRole('alert')).toContainText('Published-release metadata temporarily unavailable.')
  await expect(page.getByRole('heading', { name: 'Explorer unavailable' })).toBeVisible()
  await expect(page.locator('.campus-figures')).toHaveCount(0)
  await expect.poll(() => page.locator('#explorer').evaluate(el => el.getBoundingClientRect().top)).toBeLessThan(200)
  await page.unroute('**/api/v1/campuses/*/release')
  await page.getByRole('button', { name: 'Try again' }).click()
  await expect(page.getByLabel('Destination', { exact: true })).toBeVisible()
  await expect.poll(() => page.locator('#explorer').evaluate(el => el.getBoundingClientRect().top)).toBeLessThan(200)
})
