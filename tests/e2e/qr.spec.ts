import { expect, test, type Page } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'

test.use({ actionTimeout: 15000, trace: 'off', screenshot: 'off', video: 'off' })
async function login(page: Page, campus: string, role = 'owner') {
  await page.goto('/admin')
  await page.getByLabel('Username', { exact: true }).fill(`browser-${role}`)
  await page.getByLabel('Password', { exact: true }).fill(process.env.SCNS_E2E_PASSWORD!)
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Admin dashboard' })).toBeVisible()
  await page.getByRole('combobox', { name: 'Assigned campus', exact: true }).selectOption({ label: campus })
  await page.getByRole('button', { name: 'QR markers', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'QR markers and printable signs', exact: true })).toBeVisible()
}
async function create(page: Page, label: string) {
  await page.getByLabel('Sign label', { exact: true }).fill(label)
  await page.getByRole('combobox', { name: 'Published target node', exact: true }).selectOption({ label: 'outdoor · Gate' })
  await page.getByRole('textbox', { name: 'Intended installation position', exact: true }).fill('Synthetic invented Main Gate position; simulated sign only.')
  const result = page.waitForResponse(r => r.url().endsWith('/qr-markers') && r.request().method() === 'POST')
  await page.getByRole('button', { name: 'Create planned marker', exact: true }).click()
  const response = await result; expect(response.status()).toBe(201)
  await expect(page.getByRole('button', { name: /Synthetic.*planned.*v1/ })).toBeVisible()
  return response.json() as Promise<{ id: string; campus_id: string; version: number }>
}
async function activate(page: Page, location = 'Main Gate') {
  await page.getByLabel('Installer', { exact: true }).fill('Synthetic operator')
  await page.getByRole('textbox', { name: 'Actual installed position', exact: true }).fill(`Simulated invented ${location} node; not a physical sign.`)
  const today = new Date().toISOString().slice(0, 10)
  await page.getByLabel('Installation date', { exact: true }).fill(today)
  await page.getByLabel('Verification date', { exact: true }).fill(today)
  await page.getByLabel('Verification evidence', { exact: true }).fill('Synthetic verification exercise only; no real-world accessibility claim.')
  await page.getByRole('button', { name: 'Record verification and activate', exact: true }).click()
  await expect(page.getByText('Installation recorded and marker activated.', { exact: true })).toBeVisible()
}

test('operations signs, explicit QR confirmation, computed route, reload and revoked fallback', async ({ page, browser }, info) => {
  const campus = `Synthetic qr fixture ${info.project.name.startsWith('mobile') ? 'mobile' : 'desktop'}`
  await login(page, campus, 'operations')
  await expect(page.getByRole('button', { name: 'Draft catalog', exact: true })).toHaveCount(0)
  const marker = await create(page, 'Synthetic Gate QR')
  await activate(page)
  for (const format of ['SVG', 'PNG', 'PDF']) {
    const download = page.waitForEvent('download')
    await page.getByRole('link', { name: `Download ${format} sign`, exact: true }).click()
    const file = await download; expect(file.suggestedFilename()).toBe(`qr-${marker.id}.${format.toLowerCase()}`)
    expect(await file.failure()).toBeNull()
  }
  const context = await browser.newContext({ viewport: page.viewportSize() ?? undefined })
  const publicPage = await context.newPage()
  try {
    let routeRequests = 0
    publicPage.on('request', r => { if (r.url().endsWith('/api/v1/routes')) routeRequests++ })
    await publicPage.goto(`/q/${marker.id}`)
    await expect(publicPage.getByRole('heading', { name: 'Synthetic Gate QR', exact: true })).toBeVisible()
    expect(routeRequests).toBe(0)
    await publicPage.getByRole('button', { name: 'I am at this marker now', exact: true }).click()
    await expect(publicPage.getByLabel('Starting point', { exact: true })).toHaveValue(`qr:${marker.id}`)
    await publicPage.getByLabel('Destination', { exact: true }).selectOption({ label: 'Library' })
    const computed = publicPage.waitForResponse(r => r.url().endsWith('/api/v1/routes'))
    await publicPage.getByRole('button', { name: 'Find walking route', exact: false }).click()
    const route = await (await computed).json()
    expect(route.distance_m).toBe(256.88); expect(route.segments).toHaveLength(3); expect(route.source_marker_id).toBe(marker.id); expect(route.source_anchor_id).toBeNull()
    await expect(publicPage.getByText('Arrive at Library.', { exact: true })).toBeVisible()
    expect(await publicPage.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await publicPage.reload()
    await expect(publicPage.getByRole('button', { name: 'I am at this marker now', exact: true })).toBeVisible()
    expect(routeRequests).toBe(1)
    await page.getByLabel('Revocation reason', { exact: true }).fill('Synthetic sign removed as part of verification exercise.')
    await page.getByRole('button', { name: 'Revoke marker', exact: true }).click()
    await expect(page.getByText('Marker revoked. Existing printed links cannot start routes.', { exact: true })).toBeVisible()
    await publicPage.getByRole('button', { name: 'Check marker again', exact: true }).click()
    await expect(publicPage.getByText('This QR marker has been revoked. Choose a manual start.', { exact: true })).toBeVisible()
    await expect(publicPage.getByRole('button', { name: 'I am at this marker now', exact: true })).toHaveCount(0)
    expect((await new AxeBuilder({ page: publicPage }).include('main').analyze()).violations).toEqual([])
    await page.getByLabel('Sign label', { exact: true }).fill('Synthetic Courtyard QR')
    await page.getByRole('combobox', { name: 'Published target node', exact: true }).selectOption({ label: 'outdoor · Courtyard' })
    await page.getByRole('textbox', { name: 'Intended installation position', exact: true }).fill('Simulated sign moved to the invented Courtyard node.')
    await page.getByRole('button', { name: 'Save changes and replan', exact: true }).click()
    await expect(page.getByRole('button', { name: /^Synthetic Courtyard QR · planned · v4/ })).toBeVisible()
    await expect(page.getByLabel('Installer', { exact: true })).toHaveValue('')
    await expect(page.getByRole('textbox', { name: 'Actual installed position', exact: true })).toHaveValue('')
    await publicPage.goto(`/q/${marker.id}`)
    await expect(publicPage.getByText(/Marker status: planned/)).toBeVisible()
    await activate(page, 'Courtyard')
    await publicPage.getByRole('button', { name: 'Check marker again', exact: true }).click()
    await expect(publicPage.getByRole('heading', { name: 'Synthetic Courtyard QR', exact: true })).toBeVisible()
    await publicPage.getByRole('button', { name: 'I am at this marker now', exact: true }).click()
    await publicPage.getByRole('combobox', { name: 'Destination', exact: true }).selectOption({ label: 'Library' })
    const reassignedRoute = publicPage.waitForResponse(r => r.url().endsWith('/api/v1/routes'))
    await publicPage.getByRole('button', { name: 'Find walking route', exact: false }).click()
    const reassigned = await (await reassignedRoute).json()
    expect(reassigned.source_marker_id).toBe(marker.id); expect(reassigned.distance_m).toBeLessThan(256.88); expect(reassigned.segments).toHaveLength(2)
    await publicPage.goto(`/q/${crypto.randomUUID()}`)
    await expect(publicPage.getByRole('alert')).toContainText('marker is unknown')
    await publicPage.getByRole('link', { name: 'Choose a manual start', exact: false }).click()
    await expect(publicPage.getByRole('heading', { name: 'Plan your walk', exact: true })).toBeVisible()
  } finally { await context.close() }
})

test('stale QR edits retain input until explicit reconciliation; reviewer inventory is read-only', async ({ page, browser }, info) => {
  const campus = `Synthetic qr conflicts fixture ${info.project.name.startsWith('mobile') ? 'mobile' : 'desktop'}`
  await login(page, campus)
  const marker = await create(page, 'Synthetic conflict sign')
  const context = await browser.newContext({ viewport: page.viewportSize() ?? undefined }), other = await context.newPage()
  try {
    await login(other, campus, 'operations')
    await other.getByRole('button', { name: /^Synthetic conflict sign · planned/ }).click()
    await page.getByLabel('Sign label', { exact: true }).fill('My retained synthetic label')
    await other.getByLabel('Sign label', { exact: true }).fill('Other operator label')
    await other.getByRole('button', { name: 'Save changes and replan', exact: true }).click()
    await expect(other.getByText('Marker saved as planned. Verify its installation before activating.', { exact: true })).toBeVisible()
    await page.getByRole('button', { name: 'Save changes and replan', exact: true }).click()
    await expect(page.getByRole('button', { name: 'Use latest version and keep my inputs', exact: true })).toBeVisible()
    await expect(page.getByLabel('Sign label', { exact: true })).toHaveValue('My retained synthetic label')
    await page.getByRole('button', { name: 'Use latest version and keep my inputs', exact: true }).click()
    await page.getByRole('button', { name: 'Save changes and replan', exact: true }).click()
    await expect(page.getByRole('button', { name: /^My retained synthetic label · planned · v3/ })).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    expect((await new AxeBuilder({ page }).include('main').analyze()).violations).toEqual([])
    await other.getByRole('button', { name: 'Sign out', exact: true }).click()
    await login(other, campus, 'reviewer_publisher')
    await other.getByRole('button', { name: /^My retained synthetic label · planned/ }).click()
    await expect(other.getByLabel('Sign label', { exact: true })).toBeDisabled()
    await expect(other.getByRole('button', { name: 'Record verification and activate', exact: true })).toHaveCount(0)
    const records = await (await other.request.get(`/api/v1/admin/campuses/${marker.campus_id}/qr-markers`)).json()
    expect(records.items[0].label).toBe('My retained synthetic label')
  } finally { await context.close() }
})
